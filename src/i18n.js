function language() {
  const lang = vscode.workspace.getConfiguration('svnTools').get('language', 'ko');
  return MESSAGES[lang] ? lang : 'ko';
}

function t(key, ...args) {
  const table = MESSAGES[language()];
  const text = table[key] !== undefined ? table[key] : MESSAGES.en[key] || key;
  return text.replace(/\{(\d+)\}/g, (_, i) => (args[i] !== undefined ? String(args[i]) : ''));
}

module.exports = { t, language };
